//! The two selected RIETAN owners. Group operations are derived from the
//! conventional settings; ORFFE uses only the identity of those settings.
use super::{CaptureLimits, GraphArchive, r80::geometry_rows, selected, verify_artifact_graph};
use serde_json::{Value, json};
use vesta_model::source7::resource_graph::orffe::R80GeometryTable;
use vesta_model::source7::resource_graph::{EdgeKind, GRAPH_GROUP};
use vesta_model::{Cell3, Error, Ids, ImageKey, PersistentResource, Result, digest};

type Matrix = [[i32; 3]; 3];
const IDENTITY: Matrix = [[1, 0, 0], [0, 1, 0], [0, 0, 1]];

pub fn is_rietan_source(raw: &[u8]) -> bool {
    matches!(
        digest(raw).as_str(),
        selected::FAPATITE_INS | selected::AGI_LST
    )
}

fn invalid() -> Error {
    Error::new(
        "E_REOPEN_OWNER",
        "unqualified RIETAN source phase, setting or result binding",
    )
}

fn values<const N: usize>(row: &str) -> Result<[f64; N]> {
    let mut words = row.split_ascii_whitespace();
    let mut result = [0.; N];
    for value in &mut result {
        *value = words
            .next()
            .and_then(|word| word.parse::<f64>().ok())
            .filter(|number| number.is_finite())
            .ok_or_else(invalid)?;
    }
    Ok(result)
}

// P 63/m is generated by the 6_3 screw and inversion in the selected setting.
// I m -3 m consists of signed permutations and the body-centring translation.
fn operations(hexagonal: bool) -> Vec<(Matrix, [i32; 3])> {
    let mut operations = Vec::new();
    if hexagonal {
        let mut rotation = IDENTITY;
        for power in 0..6 {
            for sign in [1, -1] {
                operations.push((
                    rotation.map(|row| row.map(|entry| sign * entry)),
                    [0, 0, power % 2],
                ));
            }
            let [x, y, z] = rotation;
            rotation = [std::array::from_fn(|i| x[i] - y[i]), x, z];
        }
    } else {
        for centre in [0, 1] {
            for permutation in [
                [0, 1, 2],
                [0, 2, 1],
                [1, 0, 2],
                [1, 2, 0],
                [2, 0, 1],
                [2, 1, 0],
            ] {
                for signs in 0..8 {
                    let mut matrix = [[0; 3]; 3];
                    for axis in 0..3 {
                        matrix[axis][permutation[axis]] =
                            if signs & (1 << axis) == 0 { 1 } else { -1 };
                    }
                    operations.push((matrix, [centre; 3]));
                }
            }
        }
    }
    operations
}

fn site(ids: &mut Ids, label: &str, raw: &str, data: [f64; 5], mode: &str) -> Result<Value> {
    let [occupancy, x, y, z, displacement] = data;
    let element = raw.trim_end_matches(|ch: char| ch.is_ascii_digit() || matches!(ch, '+' | '-'));
    if !vesta_model::element(element) || !(0. ..=1.).contains(&occupancy) || displacement < 0. {
        return Err(invalid());
    }
    let (value, charge) = match raw {
        "O-" | "F-" => (element, json!(-1)),
        "Ca2+" => (element, json!(2)),
        _ => (element, Value::Null),
    };
    let adp = if mode == "iso-B" {
        json!({"kind":mode,"bA2":displacement})
    } else {
        json!({"kind":mode,"uA2":displacement})
    };
    Ok(json!({"id":ids.next_id(),"label":label,
        "species":{"element":value,"charge":charge,"massNumber":null,"rawToken":raw},
        "fractional":[x,y,z],"occupancy":occupancy,"adp":adp,"sourceSpans":[]}))
}

fn phase(raw: &[u8], key: &str, ids: &mut Ids) -> Result<Value> {
    let text = selected::ascii(raw, key)?;
    let hexagonal = digest(raw) == selected::FAPATITE_INS;
    let (name, symbol, hall, setting, cell, sites) = if hexagonal {
        let cell = values::<6>(
            text.lines()
                .find_map(|line| line.strip_prefix("CELLQ "))
                .ok_or_else(invalid)?,
        )?;
        let start = text
            .lines()
            .position(|line| line.starts_with("O1/O- "))
            .ok_or_else(invalid)?;
        let mut sites = Vec::new();
        for line in text.lines().skip(start).take(7) {
            let (name, tail) = line.split_once(' ').ok_or_else(invalid)?;
            let (label, raw) = name.split_once('/').ok_or_else(invalid)?;
            sites.push(site(ids, label, raw, values(tail)?, "iso-B")?);
        }
        ("Fapatite", "P 63/m", "-P 6c", "176:1", cell, sites)
    } else if digest(raw) == selected::AGI_LST {
        let cell = text
            .split_once("alpha     beta      gamma        V")
            .and_then(|(_, tail)| tail.lines().nth(1))
            .ok_or_else(invalid)?;
        let rows = text
            .split_once(
                "Structure parameters, g, x, y, z, B/Angstrom**2, and U/Angstrom**2, in AgI",
            )
            .ok_or_else(invalid)?
            .1;
        let mut sites = Vec::new();
        for (index, label, element) in [(4, "Ag1", "Ag"), (6, "I1", "I")] {
            let row = rows.lines().nth(index).ok_or_else(invalid)?;
            let columns: Vec<_> = row.split_ascii_whitespace().collect();
            if columns.len() != 13 || columns[0] != label {
                return Err(invalid());
            }
            let data =
                values(&[columns[6], columns[8], columns[9], columns[10], columns[12]].join(" "))?;
            // The selected report's last two columns are B and U. Use the explicit U value.
            sites.push(site(ids, label, element, data, "iso-U")?);
        }
        ("AgI", "I m -3 m", "-I 4 2 3", "229:1", values(cell)?, sites)
    } else {
        return Err(invalid());
    };
    let [a, b, c, alpha, beta, gamma] = cell;
    let cell = Cell3 {
        length_a: [a, b, c],
        angles_deg: [alpha, beta, gamma],
    };
    cell.validate()?;
    let rational = |numerator| json!({"numerator":numerator,"denominator":1});
    let operators: Vec<_> = operations(hexagonal).into_iter().map(|(matrix, shift)| json!({
        "id":ids.next_id(), "fractionalMatrix":matrix.map(|row| row.map(rational)),
        "fractionalTranslation":shift.map(|n| if n == 0 { rational(0) } else { json!({"numerator":n,"denominator":2}) }),
        "timeSign":1
    })).collect();
    Ok(json!({
        "id":ids.next_id(),"label":name,"parent":null,"rotation":IDENTITY,"translationA":[0,0,0],
        "fieldIds":[],"shapeId":null,
        "structure":{"cell":cell,"sites":sites,"covariance":null,
            "group":{"kind":"ordinary","symbol":symbol,"hallSymbol":hall,"bnsNumber":null,"ogNumber":null,
                "settingName":setting,"originChoice":"1","changeOfBasis":IDENTITY,"originFractional":[0,0,0],
                "table":null,"operators":operators,"sourceSpans":[]}}
    }))
}

pub(crate) fn read_rietan_phase(archive: &GraphArchive, ids: &mut Ids) -> Result<Value> {
    verify_artifact_graph(&archive.graph, &archive.files, CaptureLimits::default())?;
    let key = &archive.graph.root_key;
    phase(archive.files.get(key).ok_or_else(invalid)?, key, ids)
}

fn id(value: &Value) -> Result<&str> {
    value
        .as_str()
        .filter(|id| vesta_model::valid_id(id))
        .ok_or_else(invalid)
}

pub(crate) fn binding(
    archive: &GraphArchive,
    phase_value: &Value,
    resources: &[PersistentResource],
) -> Result<Option<R80GeometryTable>> {
    let mut expected = read_rietan_phase(archive, &mut Ids::new([0; 16]))?;
    expected["id"] = json!(id(&phase_value["id"])?);
    for pointer in ["/structure/sites", "/structure/group/operators"] {
        let fresh = phase_value
            .pointer(pointer)
            .and_then(Value::as_array)
            .ok_or_else(invalid)?;
        let rows = expected
            .pointer_mut(pointer)
            .and_then(Value::as_array_mut)
            .ok_or_else(invalid)?;
        if rows.len() != fresh.len() {
            return Err(invalid());
        }
        for (definition, current) in rows.iter_mut().zip(fresh) {
            definition["id"] = json!(id(&current["id"])?);
        }
    }
    if &expected != phase_value {
        return Err(invalid());
    }

    let edges = archive.graph.edges.as_slice();
    if edges.is_empty() {
        return Ok(None);
    }
    let [edge] = edges else {
        return Err(invalid());
    };
    let root = &archive.graph.root_key;
    if &edge.from_key != root || edge.kind != EdgeKind::GeometryImport || edge.recursive_decode {
        return Err(invalid());
    }
    let key = &edge.to_key;
    let index = archive
        .graph
        .files
        .iter()
        .position(|file| &file.key == key)
        .ok_or_else(invalid)?;
    let graph =
        serde_json::to_value(&archive.graph).map_err(|e| Error::new("E_SCHEMA", e.to_string()))?;
    let graph_digest = digest(&vesta_model::source_audit::canonical(&graph));
    let resource_key = format!("{GRAPH_GROUP}/{graph_digest}/file/{index}");
    let source = archive.files.get(root).ok_or_else(invalid)?;
    let table = archive.files.get(key).ok_or_else(invalid)?;
    let table_sha256 = digest(table);
    let resource = resources
        .iter()
        .find(|row| {
            row.logical_key == resource_key
                && row.sha256 == table_sha256
                && row.byte_length == table.len().to_string()
        })
        .ok_or_else(invalid)?;
    let phase = id(&phase_value["id"])?;
    let op = id(&phase_value["structure"]["group"]["operators"][0]["id"])?;
    let sites = phase_value["structure"]["sites"]
        .as_array()
        .ok_or_else(invalid)?;
    let site_ids = sites
        .iter()
        .map(|site| id(&site["id"]))
        .collect::<Result<Vec<_>>>()?;
    let rows = geometry_rows(
        selected::parse_orffe(source, table, key, &mut CaptureLimits::default())?,
        |site| ImageKey {
            phase: phase.to_owned().into(),
            site: site_ids[site].to_owned().into(),
            op: op.to_owned().into(),
            shift: [0; 3],
        },
    )?;
    Ok(Some(R80GeometryTable {
        owner: phase.to_owned().into(),
        resource: resource.id.clone(),
        primary_sha256: digest(source),
        table_sha256,
        rows,
    }))
}
